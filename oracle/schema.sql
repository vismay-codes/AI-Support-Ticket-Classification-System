-- Run this script once in the Oracle schema used by the application.

CREATE TABLE SUPPORT_TICKETS (
    TICKET_ID VARCHAR2(36) PRIMARY KEY,
    TICKET_TEXT VARCHAR2(1000) NOT NULL,
    CATEGORY VARCHAR2(50) NOT NULL,
    CONFIDENCE NUMBER(6,5) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL
);

CREATE INDEX IDX_SUPPORT_TICKETS_CATEGORY
    ON SUPPORT_TICKETS (CATEGORY);

-- Example analysis query:
SELECT CATEGORY, COUNT(*) AS TOTAL_TICKETS
FROM SUPPORT_TICKETS
GROUP BY CATEGORY
ORDER BY TOTAL_TICKETS DESC;
